// Diagnosis Report page (Phase 16) — a clean, printable/shareable summary
// of a single diagnosis record. Uses window.print() for "export to PDF"
// (no extra library needed — avoids over-engineering per project constraints).
import { navbarHtml, footerHtml, backLink, setupNavbarToggle } from '../components/layout.js';
import { api } from '../api.js';
import { escapeHtml, listHtml, severityClass, timeAgo, qs } from '../utils.js';
import { errorStateHtml } from '../components/diagnosisView.js';

export async function renderReport(app, id) {
  app.innerHTML = `
  <div class="page-shell">
    <div class="no-print">
      ${navbarHtml('')}
    </div>
    <main class="page-main">
      <div class="page-container no-print">${backLink('Back to Dashboard')}</div>
      <div id="report-content" class="page-container"><div class="skeleton" style="height:200px;"></div></div>
    </main>
    <div class="no-print">${footerHtml()}</div>
  </div>`;

  setupNavbarToggle();

  const res = await api.getHistoryItem(id);
  const el = qs('report-content');
  if (!res.ok) {
    el.innerHTML = errorStateHtml(res.data.error || 'Report not found.', null);
    return;
  }

  const r = res.data;
  const label = r.is_healthy ? 'Healthy' : r.disease_name;

  el.innerHTML = `
  <div class="report-page card">
    <div class="report-header">
      <div>
        <h2 class="mb-0"><i class="fas fa-leaf" aria-hidden="true"></i> PlantGuard Diagnosis Report</h2>
        <p class="text-muted mt-1 mb-0">Generated ${new Date().toLocaleString()}</p>
      </div>
      <button class="btn btn-primary no-print" onclick="window.print()"><i class="fas fa-print" aria-hidden="true"></i> Print / Save PDF</button>
    </div>

    <h3>${escapeHtml(r.plant_name)} &mdash; ${escapeHtml(label)}</h3>
    <p class="text-muted">Diagnosed ${timeAgo(r.created_at)} &middot; Record #${r.id}</p>

    <div class="row gap-3 wrap mt-2">
      <span class="badge badge-confidence-${r.confidence_level || 'medium'}">${(r.confidence_level || 'medium').toUpperCase()} CONFIDENCE (${Math.round(r.confidence)}%)</span>
      ${!r.is_healthy ? `<span class="badge badge-${severityClass(r.severity)}">${escapeHtml(r.severity)} Severity</span>` : ''}
    </div>

    ${
      !r.is_healthy
        ? `
      <div class="grid-2 mt-4">
        <div class="info-block"><h5><i class="fas fa-magnifying-glass" aria-hidden="true"></i> Symptoms</h5><ul>${listHtml(r.symptoms)}</ul></div>
        <div class="info-block"><h5><i class="fas fa-satellite-dish" aria-hidden="true"></i> How It Spreads</h5><ul>${listHtml(r.spread)}</ul></div>
        <div class="info-block"><h5><i class="fas fa-pump-medical" aria-hidden="true"></i> Treatment</h5><ul>${listHtml(r.treatment)}</ul></div>
        <div class="info-block"><h5><i class="fas fa-shield-halved" aria-hidden="true"></i> Prevention</h5><ul>${listHtml(r.prevention)}</ul></div>
      </div>`
        : `<div class="callout callout-success mt-4"><i class="fas fa-circle-check" aria-hidden="true"></i><div>No signs of disease detected at the time of this scan.</div></div>`
    }

    ${
      r.secondary_possibilities && r.secondary_possibilities.length
        ? `<div class="info-block mt-4"><h5><i class="fas fa-list-check" aria-hidden="true"></i> Other Possibilities Considered</h5><ul>${r.secondary_possibilities
            .map((s) => `<li>${escapeHtml(s.disease_name)} (${Math.round(s.confidence)}%)</li>`)
            .join('')}</ul></div>`
        : ''
    }

    <div class="report-disclaimer">
      This report was generated by an AI vision model and deterministic validation rules. It is intended
      as a helpful starting point, not a substitute for professional agronomic diagnosis. Confidence level
      reflects the AI's own estimate and is not a calibrated statistical probability.
    </div>
  </div>`;
}
